DROP TABLE IF EXISTS "film_genre";
DROP TABLE IF EXISTS "user_films";
DROP TABLE IF EXISTS "user_friends";
DROP TABLE IF EXISTS "useful";
DROP TABLE IF EXISTS "film_director";
DROP TABLE IF EXISTS "director";
DROP TABLE IF EXISTS "feed";
DROP TABLE IF EXISTS "reviews";
DROP TABLE IF EXISTS "film";
DROP TABLE IF EXISTS "user";
DROP TABLE IF EXISTS "mpa_rating";
DROP TABLE IF EXISTS "genre";

CREATE TABLE IF NOT EXISTS "genre" (
ID INTEGER NOT NULL AUTO_INCREMENT,
NAME VARCHAR NOT NULL,
CONSTRAINT NEWTABLE_PK PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS "mpa_rating" (
	ID INTEGER NOT NULL AUTO_INCREMENT,
	NAME VARCHAR NOT NULL,
	CONSTRAINT MPA_RATING_PK PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS "user" (
	ID INTEGER NOT NULL AUTO_INCREMENT,
	EMAIL VARCHAR NOT NULL,
	LOGIN VARCHAR NOT NULL,
	NAME VARCHAR,
	BIRTHDAY DATE NOT NULL,
	CONSTRAINT USER_PK PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS "film" (
	ID INTEGER NOT NULL AUTO_INCREMENT,
	NAME VARCHAR NOT NULL,
	DESCRIPTION VARCHAR(200),
	RELEASE_DATE DATE NOT NULL,
	DURATION INTEGER NOT NULL,
	RATING_ID INTEGER,
	CONSTRAINT FILM_PK PRIMARY KEY (ID),
	CONSTRAINT FILM_MPA_RATING_FK FOREIGN KEY (RATING_ID) REFERENCES "mpa_rating"(ID)
);

CREATE TABLE IF NOT EXISTS "film_genre" (
	FILM_ID INTEGER NOT NULL,
	GENRE_ID INTEGER NOT NULL,
	CONSTRAINT FILM_GENRE_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES "film"(ID) ON DELETE CASCADE,
	CONSTRAINT FILM_GENRE_GENRE_FK FOREIGN KEY (GENRE_ID) REFERENCES "genre"(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "user_films" (
	USER_ID INTEGER NOT NULL,
	FILM_ID INTEGER NOT NULL,
	CONSTRAINT USER_FILMS_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES "film"(ID) ON DELETE CASCADE,
	CONSTRAINT USER_FILMS_USER_FK FOREIGN KEY (USER_ID) REFERENCES "user"(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "user_friends" (
	USER_ID INTEGER NOT NULL,
	FRIEND_ID INTEGER NOT NULL,
	STATUS BOOLEAN DEFAULT false,
	CONSTRAINT USER_FRIENDS_USER_FK FOREIGN KEY (USER_ID) REFERENCES "user"(ID) ON DELETE CASCADE,
	CONSTRAINT USER_FRIENDS_USER_FK_1 FOREIGN KEY (FRIEND_ID) REFERENCES "user"(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "reviews" (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT VARCHAR,
    IS_POSITIVE BOOLEAN,
    USER_ID INT NOT NULL,
    FILM_ID INT NOT NULL,
    CONSTRAINT REVIEWS_USER_FK FOREIGN KEY (USER_ID) REFERENCES "user"(ID) ON DELETE CASCADE,
    CONSTRAINT REVIEWS_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES "film"(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "useful" (
    REVIEW_ID INT NOT NULL,
    IS_LIKE BOOLEAN,
    USER_ID INT NOT NULL,
    CONSTRAINT USEFUL_REVIEW_FK FOREIGN KEY (REVIEW_ID) REFERENCES "reviews"(ID) ON DELETE CASCADE,
    CONSTRAINT USEFUL_USER_FK FOREIGN KEY (USER_ID) REFERENCES "user"(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS "feed" (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTITY_ID INT NOT NULL,
    USER_ID INT NOT NULL,
    TIME_STAMP BIGINT NOT NULL,
    EVENT_TYPE VARCHAR NOT NULL,
    OPERATION VARCHAR NOT NULL,
    CONSTRAINT FEED_USER_FK FOREIGN KEY (USER_ID) REFERENCES "user"(ID) ON DELETE CASCADE
);

MERGE INTO "genre"
