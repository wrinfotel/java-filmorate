KEY(ID, NAME)
VALUES (1, 'G'),
  (2, 'PG'),
  (3, 'PG-13'),
  (4, 'R'),
  (5, 'NC-17');

CREATE TABLE IF NOT EXISTS "director" (
ID INTEGER NOT NULL AUTO_INCREMENT,
NAME VARCHAR NOT NULL,
CONSTRAINT DIRECTOR_PK PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS "film_director" (
	FILM_ID INTEGER NOT NULL,
	DIRECTOR_ID INTEGER NOT NULL,
	CONSTRAINT FILM_DIRECTOR_FILM_FK FOREIGN KEY (FILM_ID) REFERENCES "film"(ID) ON DELETE CASCADE,
	CONSTRAINT FILM_DIRECTOR_DIRECTOR_FK FOREIGN KEY (DIRECTOR_ID) REFERENCES "director"(ID) ON DELETE CASCADE
);

